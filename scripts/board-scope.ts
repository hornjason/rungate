#!/usr/bin/env bun
/**
 * `rungate board-scope [--spec <path>] [--json]` — #2275.
 *
 * Read-only. Before a maintainer opts an existing spec into the board, this
 * prints what each spec holds: its criteria, how many are ticked, whether it
 * has a placement table, and its `board:` setting. Each unticked criterion
 * gets a looks-done HINT when a test claims its id (`onboardingHint`), or says
 * why it cannot tell. Measured on two consumer repos (2026-11-16): 18 of 59
 * unticked criteria were already done and nothing ticks them, so the
 * checkboxes alone cannot say what is left.
 *
 * It never ticks anything. Ticking stays a person's act, with evidence, and
 * `audit-spec-evidence` already refuses a tick that names no proof.
 *
 * A spec with criteria that is not opted in is listed as NOT TRACKED, a
 * population of its own, so "not on the board" never reads as "done".
 */
import { readFileSync } from "fs";
import { join, relative } from "path";
import { parseArgs } from "util";
import { specPathSweep } from "../lib/board-mirror";
import { readDerivedDeclaration } from "../lib/derived-spec";
import { isTemplateSpec } from "../lib/sc-ids";
import { parseCriteria } from "../lib/spec-evidence";
import { boardDeclaration, onboardingHint, parsePlacementRows, tracksOnBoard, type OnboardingHint } from "../lib/spec-placement";
import { claimedScKeys, scopedKey } from "./sync-sc-status";

/** The one exit code every refusal routes through. */
export const REFUSE_EXIT = 1;

export interface SpecScope {
  path: string;
  scope: string;
  tracked: boolean;
  criteria: number;
  ticked: number;
  placementTable: boolean;
  /** Why the `board:` declaration could not be taken as written, by name — empty when it could. */
  boardProblems: string[];
  /** The generator a `generated-by:` copy names: listed, never counted as not tracked. */
  generated?: string;
  hints: { id: string; hint: OnboardingHint }[];
}

/** Why `--spec` may not be opted in, or null. A template's ids are placeholders; a generated copy is not the source. */
export function optInRefusal(path: string, content: string): string | null {
  if (isTemplateSpec(path)) return `${path} is the spec template; its ids are placeholders, so it is never opted in`;
  const derived = readDerivedDeclaration(content);
  if (derived.status === "derived") {
    return `${path} is generated by ${derived.generator}; opt in the source it is generated from, not this copy`;
  }
  return null;
}

/** Every spec in the sweep, or the one named, read for onboarding. */
export function boardScope(root: string, only?: string): { specs: SpecScope[] } | { refusal: string } {
  if (only !== undefined) {
    let content: string;
    try {
      content = readFileSync(join(root, only), "utf-8");
    } catch (e) {
      return { refusal: `${only} could not be read (${(e as Error).message})` };
    }
    const refused = optInRefusal(only, content);
    if (refused !== null) return { refusal: refused };
  }
  const sweep = specPathSweep(root);
  if (sweep.reading === "UNMEASURED") return { refusal: `UNMEASURED: the specs/ sweep failed: ${sweep.unmeasuredReasons.join("; ")}` };
  if (only !== undefined && !sweep.paths.includes(only)) return { refusal: `${only} is not a spec the sweep reads under specs/` };

  const texts = new Map(sweep.paths.map(p => [p, readFileSync(join(root, p), "utf-8")]));
  const declaredBy = new Map<string, string[]>();
  for (const [p, text] of texts) {
    for (const c of parseCriteria(text)) declaredBy.set(c.id, [...(declaredBy.get(c.id) ?? []), p]);
  }
  const claimed = claimedScKeys(join(root, "specs"), join(root, "test"));

  const specs: SpecScope[] = [];
  for (const path of only === undefined ? sweep.paths : [only]) {
    const text = texts.get(path)!;
    const board = boardDeclaration(text);
    const criteria = parseCriteria(text);
    const derived = readDerivedDeclaration(text);
    const specFile = relative(join(root, "specs"), join(root, path));
    const isClaimed = (id: string) => claimed.has(scopedKey(specFile, id));
    specs.push({
      path,
      scope: board.scope,
      tracked: tracksOnBoard(board),
      boardProblems: [...board.problems, ...board.unknownKeys.map(k => `\`board.${k}\` is not a key the engine knows`)],
      criteria: criteria.length,
      ticked: criteria.filter(c => c.ticked).length,
      placementTable: parsePlacementRows(text).length > 0,
      ...(derived.status === "derived" ? { generated: derived.generator } : {}),
      hints: criteria.filter(c => !c.ticked).map(c => ({ id: c.id, hint: onboardingHint(c.id, path, isClaimed, declaredBy) })),
    });
  }
  return { specs };
}

function hintText(h: OnboardingHint): string {
  if (h.kind === "looks-done") return "looks done: a test claims it. Tick it yourself, with proved-by:, if it is";
  if (h.kind === "ambiguous") return `ambiguous: also stated by ${h.others.join(", ")}`;
  return `cannot tell: ${h.why}`;
}

export function formatScope(specs: readonly SpecScope[], named = false): string {
  const lines: string[] = [];
  // A spec asked for by name is always shown, criteria or not (review of #2329).
  const shown = (x: SpecScope) => named || x.criteria > 0;
  for (const s of specs.filter(x => shown(x) && x.generated !== undefined)) {
    lines.push(`${s.path} — generated by ${s.generated}; opt in its source, so it is not counted`);
  }
  for (const s of specs.filter(x => shown(x) && x.generated === undefined)) {
    const state = s.tracked ? `tracked (${s.scope})` : `NOT TRACKED (${s.scope})`;
    lines.push(`${s.path} — ${state}: ${s.criteria} criteria, ${s.ticked} ticked, placement table: ${s.placementTable ? "yes" : "no"}`);
    // A board: block that cannot be read is named, never shown as merely untracked.
    for (const p of s.boardProblems) lines.push(`  board: ${p}`);
    for (const { id, hint } of s.hints) lines.push(`  ${id}  ${hintText(hint)}`);
  }
  const untracked = specs.filter(s => s.criteria > 0 && !s.tracked && s.generated === undefined);
  lines.push(
    "",
    `not tracked: ${untracked.length} spec(s), ${untracked.reduce((n, s) => n + s.criteria, 0)} criteria the board does not show`,
  );
  return lines.join("\n");
}

function main(argv: string[], root = process.cwd()): number {
  let values: { spec?: string; json?: boolean };
  try {
    ({ values } = parseArgs({ args: argv, options: { spec: { type: "string" }, json: { type: "boolean" } }, strict: true }));
  } catch (e) {
    console.error(`board-scope: ${(e as Error).message}`);
    return REFUSE_EXIT;
  }
  const read = boardScope(root, values.spec);
  if ("refusal" in read) {
    console.error(`board-scope: ${read.refusal}`);
    return REFUSE_EXIT;
  }
  console.log(values.json ? JSON.stringify(read.specs, null, 2) : formatScope(read.specs, values.spec !== undefined));
  return 0;
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
